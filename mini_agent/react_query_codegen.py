"""Scaffold React Query hooks around openapi-fetch using openapi-react-query."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from langchain.tools import tool

from . import dev_environment as dev
from . import fullstack_codegen as codegen
from . import sandbox
from .result import ToolResult


def generate_react_query_hooks(
    *, workspace: Path, frontend_path: str = "frontend",
    client_path: str = "frontend/src/api-client.ts",
    output_path: str = "frontend/src/api-hooks.ts",
) -> ToolResult:
    """Generate a reusable typed $api hooks module from an existing API client.

    openapi-react-query owns the generic HTTP method/path/params types.
    """
    root = workspace.resolve()
    frontend = dev._project(root, frontend_path)
    dev._manager(frontend, "node")
    client = sandbox.resolve_path(client_path, root)
    target = sandbox.resolve_path(output_path, root)
    if not client.is_relative_to(frontend) or not client.is_file() or client.suffix != ".ts":
        raise FileNotFoundError("请先用 generate_typed_api_client 创建前端 TypeScript API 客户端")
    if not target.is_relative_to(frontend) or target.name.endswith(".d.ts") or target.suffix != ".ts":
        raise ValueError("React Query hooks 输出必须是前端项目内的 .ts 文件")
    if target == client:
        raise ValueError("Hooks 输出不能覆盖 API 客户端")
    if not target.parent.is_dir():
        raise FileNotFoundError("Hooks 输出目录不存在，请先创建")
    package = dev._manifest(frontend) or {}
    deps = package.get("dependencies", {})
    dev_deps = package.get("devDependencies", {})
    declared: set[str] = set()
    for group in (deps, dev_deps):
        if isinstance(group, dict):
            declared.update(group)
    missing = {"openapi-fetch", "openapi-react-query", "@tanstack/react-query"} - declared
    if missing:
        raise ValueError("请先在 package.json 声明依赖: " + ", ".join(sorted(missing)))
    module = codegen._types_module_import(client, target)
    text = (
        "// Generated by mini-agent; typed React Query integration.\n"
        'import createClient from "openapi-react-query";\n'
        f'import {{ api }} from {json.dumps(module)};\n\n'
        "export const $api = createClient(api);\n"
        "// In React components call $api.useQuery('get', '/path', options).\n"
        "// For mutations call $api.useMutation('post', '/path').\n"
        "// Provide QueryClientProvider at the application root.\n"
    )
    payload = sandbox.encode_content(text)
    with sandbox.file_change({target: payload}, root):
        sandbox.atomic_write_bytes(target, payload)
    location = target.relative_to(root).as_posix()
    return ToolResult(
        sandbox.redact_text(json.dumps({
            "output": location, "client": client.relative_to(root).as_posix(),
            "hooks": ["$api.useQuery", "$api.useMutation", "$api.useSuspenseQuery", "$api.queryOptions"],
            "provider": "@tanstack/react-query QueryClientProvider",
        }, ensure_ascii=False)),
        "success", "react_query_hooks_generated", {"output": location, "bytes": len(payload)},
    )


def build_react_query_tools(workspace: Path) -> list[Any]:
    root = workspace.resolve()

    @tool(response_format="content_and_artifact")
    def generate_react_query_hooks_tool(
        frontend_path: str = "frontend",
        client_path: str = "frontend/src/api-client.ts",
        output_path: str = "frontend/src/api-hooks.ts",
    ) -> tuple[str, dict[str, Any]]:
        """Generate typed React Query hooks backed by the existing OpenAPI client.

        Requires package.json to declare openapi-react-query, openapi-fetch and
        @tanstack/react-query. Output .ts file can be newly created or updated.
        """
        outcome = generate_react_query_hooks(
            workspace=root, frontend_path=frontend_path,
            client_path=client_path, output_path=output_path,
        )
        return dev._outcome(outcome)

    generate_react_query_hooks_tool.name = "generate_react_query_hooks"
    generate_react_query_hooks_tool.metadata = {
        "risk": "write", "mutation": True,
        "workspace_arguments": ("frontend_path", "client_path", "output_path"),
        "mutation_paths": ("output_path",),
    }
    return [generate_react_query_hooks_tool]
